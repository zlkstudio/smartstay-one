<?php
declare(strict_types=1);

// Generates the VAPID key pair for push notifications → config/push.php (chmod 600). Run once.
// Usage: php bin/push-keys.php [--subject=mailto:contact@radoiromeo.ro] [--force]
// --force makes NEW keys: every device must then re-enable notifications (Jurnal → Activează).

if (PHP_SAPI !== 'cli') {
    exit(1);
}
require dirname(__DIR__) . '/src/bootstrap.php';

use One\Notify\WebPush;

$opts = getopt('', ['subject::', 'force']);
$path = ONE_ROOT . '/config/push.php';
if (is_file($path) && !isset($opts['force'])) {
    fwrite(STDERR, "config/push.php există deja — nimic de făcut. (--force = chei noi, toate telefoanele se reabonează)\n");
    exit(0);
}
$subject = (string) ($opts['subject'] ?? 'mailto:contact@radoiromeo.ro');
if (!preg_match('#^(mailto:|https://)#', $subject)) {
    fwrite(STDERR, "--subject trebuie să înceapă cu mailto: sau https://\n");
    exit(1);
}

$keys = WebPush::generateKeys();
$php = "<?php\n// VAPID keys for push notifications — generated by bin/push-keys.php. Never commit.\ndeclare(strict_types=1);\n\nreturn "
    . var_export(['public_key' => $keys['public_key'], 'private_key_pem' => $keys['private_key_pem'], 'subject' => $subject], true) . ";\n";
if (file_put_contents($path, $php, LOCK_EX) === false) {
    fwrite(STDERR, "Nu pot scrie $path\n");
    exit(1);
}
chmod($path, 0600);
echo "✔ config/push.php creat (chmod 600). Cheia publică: {$keys['public_key']}\n";
